#!/usr/bin/env node
// Bake docs/summary-2026-05-09/index-light.html into src/app/summary/summary-html.ts
// so the /summary route handler can serve it as a self-contained static HTML doc.
// The source file has its own <html><head><body><script>; we don't try to render
// it through React — we wrap the bytes as a JS template literal and return them
// as text/html. Backticks and ${ inside the source must be escaped so the outer
// template doesn't try to interpolate them.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(here, '../docs/summary-2026-05-09/index-light.html')
const OUT = resolve(here, '../src/app/summary/summary-html.ts')

const src = readFileSync(SRC, 'utf8')
const escaped = src
  .replaceAll('\\', '\\\\')
  .replaceAll('`', '\\`')
  .replaceAll('${', '\\${')

const banner = `// Generated by scripts/gen-summary-html.mjs from docs/summary-2026-05-09/index-light.html.
// Do not edit by hand — re-run the script if the source HTML changes.

export const SUMMARY_HTML = `

writeFileSync(OUT, banner + '`' + escaped + '`\n')
console.log(`wrote ${OUT} (${escaped.length} bytes)`)
